async def one(t, p, v, r, pi):
    for a in range(5):
        try: await edge_tts.Communicate(t, v, rate=f'{r:+d}%', pitch=f'{pi:+d}Hz').save(p); return True
        except Exception: await asyncio.sleep(2 * (a + 1))
    return False
def dur(p):
    try: return round(float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p]).decode().strip()), 2)
    except Exception: return 3.0
async def main():
    os.makedirs(D, exist_ok=True)
    jobs = []
    for who, ls in NAMED.items():
        for i, t in enumerate(ls): jobs.append(('n_%s_%d' % (who, i), who, t))
    for c, ls in CAT.items():
        for i, t in enumerate(ls): jobs.append(('c_%s_%d' % (c, i), 'g%d' % (i % 5 if c not in ('bar',) else (i + 3) % 5), t))
    for k, (who, t) in GAG.items():
        if t: jobs.append((k, who, t))
    sem = asyncio.Semaphore(6); bad = []
    async def run(k, who, t):
        p = os.path.join(D, k + '.mp3')
        async with sem:
            if not os.path.exists(p) or os.path.getsize(p) < 500:
                v, r, pi = ST[who]
                if not await one(t, p, v, r, pi): bad.append(k)
    await asyncio.gather(*[run(*j) for j in jobs])
    out = {'named': {}, 'cat': {}, 'lines': {}}
    for k, who, t in jobs:
        p = os.path.join(D, k + '.mp3'); o = {'who': who, 'ja': t, 'file': 'pal/' + k + '.mp3', 'dur': dur(p)} if os.path.exists(p) else {'who': who, 'ja': t, 'dur': max(2, len(t) * 0.12)}
        out['lines'][k] = o
        if k.startswith('n_'): out['named'].setdefault(who, []).append(k)
        elif k.startswith('c_'): out['cat'].setdefault(k.split('_')[1], []).append(k)
    with open(os.path.join(ROOT, 'assets', 'voices', 'voices_pal.js'), 'w') as f:
        f.write('// 自動生成 (tools/add_pal_voices.py)。宮殿の日常\nwindow.VOICE_PAL = ' + json.dumps(out, ensure_ascii=False) + ';\n')
    print('lines', len(jobs), 'bad', bad)
asyncio.run(main())
